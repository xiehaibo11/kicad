// Exercise the actual patched SDK probe methods without launching a CLI or model.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const root=process.argv[2], require=createRequire(path.join(root,'package.json'));
const ts=require('typescript'), filename=path.join(root,'src/services/claude/ClaudeSdkService.ts');
const source=ts.createSourceFile(filename,fs.readFileSync(filename,'utf8'),ts.ScriptTarget.Latest,true);
const service=source.statements.find(node=>ts.isClassDeclaration(node)&&node.name?.text==='ClaudeSdkService');
const methods=service.members.filter(node=>ts.isMethodDeclaration(node)&&['probe','queryLite'].includes(node.name.getText(source))).map(node=>node.getText(source)).join('\n').replace("await import('@anthropic-ai/claude-agent-sdk')",'await fixture.sdk()');
let created=0, returned=0, blocked=false, executable=Promise.resolve('/fixture/cli'), lastOptions;
const fixture={sdk:async()=>({query:({options})=>{created++;lastOptions=options;return {wait:()=>blocked?new Promise(()=>{}):Promise.resolve('models'),return:async()=>{returned++;}};}})};
const code=`class Probe { context={subscriptions:[]}; getClaudeExecutablePath(){return fixture.path()} ${methods} }; globalThis.Probe=Probe;`;
fixture.path=()=>executable;
const scope={fixture,AbortController,setTimeout,clearTimeout,SDK_PROBE_CAPABILITIES:{fixture:query=>query.wait()},AsyncStream:class {done(){}}};
vm.runInNewContext(ts.transpileModule(code,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText,scope);
const probe=new scope.Probe();
assert.equal((await probe.probe({capabilities:['fixture']})).data.fixture,'models');
assert.equal(lastOptions.persistSession,false);assert.equal(lastOptions.abortController.signal.aborted,true);assert.equal(returned,1);assert.equal(probe.context.subscriptions.length,0);
assert.equal(lastOptions.strictMcpConfig,true);assert.deepEqual(Object.keys(lastOptions.mcpServers),[]);assert.equal(lastOptions.tools.length,0);assert.equal(lastOptions.disallowedTools[0],'Skill');assert.ok('disable-slash-commands' in lastOptions.extraArgs);
blocked=true;
await assert.rejects(probe.probe({capabilities:['fixture'],timeoutMs:1000}),/timed out/);
assert.equal(lastOptions.abortController.signal.aborted,true);assert.equal(returned,2);assert.equal(probe.context.subscriptions.length,0);
const before=created;let release;executable=new Promise(resolve=>release=resolve);
await assert.rejects(probe.probe({capabilities:['fixture'],timeoutMs:1000}),/timed out/);
release('/fixture/late-cli');await new Promise(resolve=>setTimeout(resolve,20));
assert.equal(created,before,'Late CLI resolution must not spawn an orphan');
assert.equal(probe.context.subscriptions.length,0);
console.log('SDK probe lifecycle passed: success/timeout abort, bounded lifetime and no late orphan spawn.');
