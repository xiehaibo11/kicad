function patch(file, before, after, count = 1) {
  const target = path.join(root, file);
  const source = fs.readFileSync(target, 'utf8');
  const found = source.split(before).length - 1;
  if (found !== count) throw new Error(`Workbench anchor found ${found}x (expected ${count}) in ${file}: ${before.slice(0, 80)}`);
  fs.writeFileSync(target, source.replaceAll(before, () => after));
}
function replaceBetween(file, start, end, replacement) {
  const target = path.join(root, file);
  const source = fs.readFileSync(target, 'utf8');
  const from = source.indexOf(start);
  const to = end === null ? source.length : source.indexOf(end, from + start.length);
  if (from < 0 || to < 0) throw new Error(`Workbench block missing in ${file}: ${start.slice(0, 60)}`);
  fs.writeFileSync(target, source.slice(0, from) + replacement + source.slice(end === null ? source.length : to + end.length));
}
function copy(file) {
  const destination = path.join(root, file);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.copyFileSync(path.join(overlay, file), destination);
}

