#!/usr/bin/env bash
# Generate Go protobuf bindings for the KiCad API.
#
# KiCad's proto packages form a cycle when mapped 1:1 to Go packages:
#   common/types (project_settings.proto) imports board/board_types.proto
#   board/* imports common/types and common/commands
#   common/commands imports common/types
#
# Go forbids package cycles, so we:
#   * merge common/** and board/** into one Go package, `kicadproto`
#   * keep schematic/** as its own package, `kschematic`
#
# This is done by injecting go_package options into a temporary copy of the
# proto tree; the checked-in proto files are never modified.  Output is
# generated into a staging directory and swapped in only on success, so a
# protoc failure cannot destroy the checked-in bindings.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
MODULE_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_ROOT="$(cd "$MODULE_ROOT/../../.." && pwd)"
PROTO_ROOT="$REPO_ROOT/api/proto"
OUT="$MODULE_ROOT/internal/kicadproto"
GO_PREFIX="github.com/zhoushoujianwork/easyeda-agent/kicad-agent/internal/kicadproto"
GENERATED_HEADER='// SPDX-License-Identifier: GPL-3.0-or-later
// Code generated by proto/gen.sh from KiCad api/proto. DO NOT EDIT.
'

if ! command -v protoc >/dev/null 2>&1; then
  echo "protoc not found; install protobuf (brew install protobuf)" >&2
  exit 1
fi

PLUGIN="$(go env GOPATH)/bin/protoc-gen-go"
if [ ! -x "$PLUGIN" ]; then
  echo "protoc-gen-go not found; run: go install google.golang.org/protobuf/cmd/protoc-gen-go@v1.36.6" >&2
  exit 1
fi

echo "protoc: $(protoc --version)"
echo "protoc-gen-go: $(grep -o 'protoc-gen-go v[0-9.]*' "$PLUGIN" 2>/dev/null | head -1 || echo unknown)"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
cp -R "$PROTO_ROOT"/* "$TMP"/

while IFS= read -r f; do
  rel="${f#"$TMP"/}"
  case "$rel" in
    schematic/*) pkg="$GO_PREFIX/schematic;kschematic" ;;
    *)           pkg="$GO_PREFIX;kicadproto" ;;
  esac

  PKG="$pkg" perl -0pi -e \
    's{^(package\s+[^;]+;)}{$1\noption go_package = "$ENV{PKG}";}m' "$f"
done < <(find "$TMP" -name '*.proto' -print | sort)

# Two protos with the same basename would silently produce the same output file
# in the flattened packages.
duplicates="$(find "$TMP" -name '*.proto' -print | xargs -n1 basename | sort | uniq -d)"
if [ -n "$duplicates" ]; then
  echo "duplicate proto basenames would collide in the flattened output:" >&2
  echo "$duplicates" >&2
  exit 1
fi

protos=()
while IFS= read -r p; do
  protos+=("$p")
done < <(cd "$TMP" && find . -name '*.proto' -print | sed 's|^\./||' | sort)

STAGE="$TMP/gen"
mkdir -p "$STAGE"

(cd "$TMP" && protoc -I . \
  --plugin=protoc-gen-go="$PLUGIN" \
  --go_out="$STAGE" \
  --go_opt=module="$GO_PREFIX" \
  "${protos[@]}")

# Prepend the SPDX header to every generated file.
while IFS= read -r f; do
  printf '%s' "$GENERATED_HEADER" | cat - "$f" > "$f.tmp"
  mv "$f.tmp" "$f"
done < <(find "$STAGE" -name '*.pb.go')

rm -rf "$OUT"
mv "$STAGE" "$OUT"

echo "generated $(find "$OUT" -name '*.pb.go' | wc -l | tr -d ' ') Go files under $OUT"
